"""Состояние учётной записи участника.

Общий тип для владельцев и догситтеров: правила блокировки одинаковы,
хотя агрегаты раздельные.
"""

from enum import StrEnum

__all__ = ("AccountStatus",)


class AccountStatus(StrEnum):
    """Состояние учётной записи."""

    ACTIVE = "active"
    """Учётная запись доступна, участник работает с сервисом."""

    BLOCKED = "blocked"
    """Заблокирована администратором. Новые заказы недоступны."""

    DELETED = "deleted"
    """Удалена по запросу участника. Данные обезличиваются, история заказов
    остаётся ради расчётов и отзывов."""
